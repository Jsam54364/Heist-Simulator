"""Packs the city's PBR texture sets into three Texture2DArrays (albedo / normal / ORM)
for the merged "city_uber" shader, so a whole chunk renders in one draw call instead of
one per material. Plain (untextured) materials get flat cells whose roughness/metal live
in the ORM cell. Writes assets/textures/city_{albedo,normal,orm}_array.png (+ .import)
and scripts/world/city_layers.gd (layer table used by MeshBuilder and the shader).
Run after tools/gen_assets.py, or after swapping in your own texture sets."""
from PIL import Image
S = 512
# name, texture set (None = plain), roughness, metallic, use vertex colour, emission, albedo tint
LAYERS = [
    ('facade_stucco', 'facade_stucco', 0, 0, 1, 0, (1, 1, 1)),
    ('facade_brick', 'facade_brick', 0, 0, 1, 0, (1, 1, 1)),
    ('facade_office', 'facade_office', 0, 0, 1, 0, (1, 1, 1)),
    ('facade_glass', 'facade_glass', 0, 0, 1, 0, (1, 1, 1)),
    ('shopfront', 'shopfront', 0, 0, 1, 0, (1, 1, 1)),
    ('asphalt', 'asphalt', 0, 0, 0, 0, (1, 1, 1)),
    ('sidewalk', 'sidewalk', 0, 0, 0, 0, (1, 1, 1)),
    ('roof_gravel', 'roof_gravel', 0, 0, 0, 0, (1, 1, 1)),
    ('sand', 'sand', 0, 0, 0, 0, (1, 1, 1)),
    ('grass', 'grass', 0, 0, 0, 0, (1, 1, 1)),
    ('wood_planks', 'wood_planks', 0, 0, 1, 0, (1, 1, 1)),
    ('marble', 'marble', 0, 0, 0, 0, (1, 1, 1)),
    ('carpet', 'carpet', 0, 0, 0, 0, (1, 1, 1)),
    ('checker_floor', 'checker_floor', 0, 0, 0, 0, (1, 1, 1)),
    ('plaster', 'plaster', 0, 0, 1, 0, (1, 1, 1)),
    ('concrete', 'concrete', 0, 0, 1, 0, (1, 1, 1)),
    ('metal_brushed', 'metal_brushed', 0, 0, 1, 0, (1, 1, 1)),
    ('awning', 'awning', 0.85, 0, 1, 0, (1, 1, 1)),
    ('paint', None, 0.7, 0, 1, 0, (1, 1, 1)),
    ('paint_gloss', None, 0.28, 0.25, 1, 0, (1, 1, 1)),
    ('trunk', None, 0.95, 0, 0, 0, (0.54, 0.42, 0.28)),
    ('lamp_glow', None, 0.5, 0, 0, 3.0, (1, 0.96, 0.82)),
    ('light_panel', None, 0.5, 0, 0, 1.6, (1, 1, 0.97)),
    ('line_white', None, 0.7, 0, 0, 0, (0.92, 0.92, 0.9)),
    ('line_yellow', None, 0.7, 0, 0, 0, (0.88, 0.7, 0.16)),
    ('leaf', None, 0.75, 0, 1, 0, (1, 1, 1)),
]
BACKLIGHT = {'leaf': 1.0}
alb, nrm, orm = (Image.new('RGB', (S, S * len(LAYERS))) for _ in range(3))
for i, (name, tex, r, m, vc, em, tint) in enumerate(LAYERS):
    y = i * S
    if tex == 'awning':
        alb.paste(Image.open('assets/textures/awning_albedo.png').convert('RGB').resize((S, S), Image.LANCZOS), (0, y))
        nrm.paste(Image.new('RGB', (S, S), (128, 128, 255)), (0, y))
        orm.paste(Image.new('RGB', (S, S), (255, int(r * 255), int(m * 255))), (0, y))
    elif tex:
        for img, suf in ((alb, 'albedo'), (nrm, 'normal'), (orm, 'orm')):
            img.paste(Image.open(f'assets/textures/{tex}_{suf}.png').convert('RGB').resize((S, S), Image.LANCZOS), (0, y))
    else:
        alb.paste(Image.new('RGB', (S, S), (255, 255, 255)), (0, y))
        nrm.paste(Image.new('RGB', (S, S), (128, 128, 255)), (0, y))
        orm.paste(Image.new('RGB', (S, S), (255, int(r * 255), int(m * 255))), (0, y))
for img, suf in ((alb, 'albedo'), (nrm, 'normal'), (orm, 'orm')):
    p = f'assets/textures/city_{suf}_array.png'
    img.save(p)
    with open(p + '.import', 'w') as f:
        f.write('[remap]\n\nimporter="2d_array_texture"\ntype="CompressedTexture2DArray"\n\n[params]\n\n'
                'compress/mode=2\ncompress/high_quality=false\ncompress/lossy_quality=0.7\n'
                'compress/hdr_compression=1\ncompress/channel_pack=0\nmipmaps/generate=true\nmipmaps/limit=-1\n'
                f'slices/horizontal=1\nslices/vertical={len(LAYERS)}\n')
with open('scripts/world/city_layers.gd', 'w') as f:
    f.write('class_name CityLayers\n## Generated by tools/gen_city_arrays.py - layer table for the city_uber shader.\n\n')
    f.write('const INDEX := {%s}\n' % ', '.join(f'"{n}": {i}' for i, (n, *_r) in enumerate(LAYERS)))
    f.write('const COUNT := %d\n' % len(LAYERS))
    f.write('## x: use vertex colour, y: emission energy, z: normal strength, w: foliage backlight\n')
    f.write('const PARAMS := [%s]\n' % ', '.join(f'Vector4({vc}, {em}, {0.0 if tex in (None, "awning") else 1.0}, {BACKLIGHT.get(n, 0)})' for (n, tex, r, m, vc, em, t) in LAYERS))
    f.write('const TINT := [%s]\n' % ', '.join(f'Color({t[0]}, {t[1]}, {t[2]})' for (*_a, t) in LAYERS))
print('arrays written', len(LAYERS), 'layers')
